/*
 * 启动编排：只负责按顺序初始化各层，具体实现都在各模块里
 *
 *   UI（main/UI）          界面，只读服务的数据
 *   服务（main/App）        imu / time / net / mqtt 服务 + 应用事件
 *   板级（components/board）引脚、屏幕、I2C 总线、IO 扩展、触摸、LVGL 显示
 *   驱动（components/mpu6050）
 */

#include <stdio.h>
#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_log.h"
#include "esp_heap_caps.h"
#include "nvs_flash.h"
#include "esp_lv_adapter.h"

#include "board_lcd.h"
#include "board_i2c.h"
#include "board_exio.h"
#include "board_touch.h"
#include "board_display.h"

#include "App/app_event.h"
#include "App/imu_service.h"
#include "App/time_service.h"
#include "App/net_service.h"
#include "App/mqtt_service.h"

#include "gui_guider.h"
#include "custom.h"

#define TAG "main"

// Global UI object generated by GUI Guider
lv_ui guider_ui;

// Wi-Fi, DMA and task stacks need internal RAM; if it runs low they fail first.
static void log_free_heap(const char *stage)
{
    ESP_LOGI(TAG, "Free heap after %s: internal %u KB (largest block %u KB), PSRAM %u KB", stage,
             (unsigned)(heap_caps_get_free_size(MALLOC_CAP_INTERNAL) / 1024),
             (unsigned)(heap_caps_get_largest_free_block(MALLOC_CAP_INTERNAL) / 1024),
             (unsigned)(heap_caps_get_free_size(MALLOC_CAP_SPIRAM) / 1024));
}

void app_main(void)
{
    // 1) Initialize NVS for persistent settings (such as Wi-Fi)
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES || ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    ESP_ERROR_CHECK(ret);

    // 2) Initialize app event system
    app_event_init();

    // 3) Initialize I2C bus, then the CH422G IO expander and GT911 touch on it.
    //    The expander drives the LCD reset and backlight, so it goes before the
    //    panel. Without touch the device still runs, the UI just can't be tapped.
    i2c_master_bus_handle_t i2c_bus = NULL;
    ESP_ERROR_CHECK(board_i2c_init(&i2c_bus));

    esp_lcd_touch_handle_t touch = NULL;
    if (board_exio_init(i2c_bus) != ESP_OK) {
        ESP_LOGE(TAG, "CH422G IO expander not responding, touch disabled");
    } else if (board_touch_init(i2c_bus, &touch) != ESP_OK) {
        ESP_LOGW(TAG, "Touch not available, running without touch");
        touch = NULL;
    }

    // 4) Initialize RGB LCD panel
    ESP_LOGI(TAG, "Install RGB LCD panel driver");
    esp_lcd_panel_handle_t panel_handle = NULL;
    ESP_ERROR_CHECK(board_lcd_init(&panel_handle));

    // 5) Start IMU service.
    //    Sensor init runs in the service task; if the sensor is missing the
    //    device keeps running, the UI shows offline and the service retries.
    if (imu_service_start(i2c_bus) != ESP_OK) {
        ESP_LOGE(TAG, "Failed to start IMU service");
    }

    // 6) Initialize LVGL display, bind RGB panel and touch
    ESP_ERROR_CHECK(board_display_init(panel_handle, touch, NULL));

    // 7) Build and initialize UI under LVGL lock
    if (esp_lv_adapter_lock(-1) == ESP_OK) {
        setup_ui(&guider_ui);
        custom_init(&guider_ui);
        esp_lv_adapter_unlock();
    }
    log_free_heap("UI");

    // 8) Start SNTP time sync and MQTT (both wait for IP), then connect Wi-Fi.
    //    If the broker is unreachable the device keeps running and esp-mqtt retries.
    time_service_start();
    if (mqtt_service_start() != ESP_OK) {
        ESP_LOGE(TAG, "Failed to start MQTT service");
    }
    net_service_start();
    log_free_heap("Wi-Fi start");

    // 9) Main loop (currently keeps task alive)
    while (1)
    {
        vTaskDelay(pdMS_TO_TICKS(1000));
    }
}
